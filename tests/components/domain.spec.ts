test('load conventions remain explicit, preserve machine context and enforce bodyweight semantics', async ({ page }) => {
  const coach = page.getByRole('region', { name: 'Coach set' })
  const client = page.getByRole('region', { name: 'Client set' })
  await expect(coach.getByLabel('Target load convention')).toHaveValue('Total external load')
  await expect(client.getByLabel('Actual load convention')).toHaveValue('Unknown convention')
  await client.getByLabel('Actual load (kg)').fill('20')
  for (const label of ['Per dumbbell', 'Added to bodyweight', 'Assistance', 'Machine display']) {
    await client.getByLabel('Actual load convention').click()
    await page.getByRole('option', { name: label, exact: true }).click()
    await expect(client.getByLabel('Actual load (kg)')).toHaveValue('20')
    await expect(client.getByText(`Actual: 20 kg (${label.toLowerCase()})`, { exact: false })).toBeVisible()
  }
  await expect(client.getByText(/Actual:.*Machine: unknown context/)).toBeVisible()
  await client.getByLabel('Actual machine reference', { exact: true }).fill('gym-a:press-1')
  await client.getByLabel('Actual reps', { exact: true }).fill('8')
  await client.getByLabel('Set completed').check()
  await expect(client.getByText(/Actual:.*Machine: gym-a:press-1/)).toBeVisible()
  await client.getByLabel('Actual load convention').click()
  await page.getByRole('option', { name: 'Bodyweight', exact: true }).click()
  await expect(client.getByLabel('Actual load (kg)')).toHaveValue('')
  await expect(client.getByLabel('Actual load (kg)')).toHaveAttribute('readonly', '')
  await expect(client.getByLabel('Actual machine reference', { exact: true })).toHaveCount(0)
  await expect(client.getByText(/Actual: Bodyweight · No external load recorded/)).toBeVisible()
  await client.getByLabel('Actual load convention').click()
  await page.getByRole('option', { name: 'Machine display', exact: true }).click()
  await expect(client.getByLabel('Actual machine reference', { exact: true })).toHaveValue('')
  await expect(coach.getByLabel('Load (kg)', { exact: true })).toHaveValue('60')
})

