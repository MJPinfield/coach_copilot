test('nullable actuals, zero and completion are distinct from the prescription', async ({ page }) => {
  const coach = page.getByRole('region', { name: 'Coach set' })
  const client = page.getByRole('region', { name: 'Client set' })
  await expect(client.getByLabel('Actual load (kg)')).toHaveValue('')
  await expect(client.getByLabel('Set completed')).not.toBeChecked()
  await client.getByLabel('Actual load (kg)').fill('0')
  await client.getByLabel('Actual reps', { exact: true }).fill('0')
  await expect(client.getByText('Actual: 0 kg (unknown convention) · 0 reps · RIR not recorded')).toBeVisible()
  await expect(client.getByLabel('Set completed')).not.toBeChecked()
  await client.getByLabel('Set completed').check()
  await client.getByLabel('Actual load (kg)').fill('')
  await expect(client.getByText('Actual: Load not recorded (unknown convention) · 0 reps · RIR not recorded')).toBeVisible()
  await expect(coach.getByLabel('Load (kg)', { exact: true })).toHaveValue('60')
})

test('coach superset uses one after-round rest and clients retain separate exercise results', async ({ page }) => {
  const section = page.locator('#superset')
  await section.locator('label').filter({ hasText: /^Coach$/ }).click()
  await expect(section.getByLabel('Rest after complete round (s)')).toHaveCount(1)
  await expect(section.getByLabel('Rest after set (s)')).toHaveCount(0)
  await section.getByLabel('Rest after complete round (s)').fill('120')
  await section.locator('label').filter({ hasText: /^Client$/ }).click()
  const round1 = section.getByRole('group', { name: 'Round 1', exact: true })
  const round2 = section.getByRole('group', { name: 'Round 2', exact: true })
  const first = round1.getByRole('article', { name: 'A1 Barbell bench press' })
  const second = round1.getByRole('article', { name: 'A2 Barbell bent over row' })
  await first.getByLabel('Actual load (kg)').fill('52.5')
  await first.getByLabel('Actual reps', { exact: true }).fill('7')
  await first.getByLabel('Actual load convention', { exact: true }).click()
  await page.getByRole('option', { name: 'Total external load', exact: true }).click()
  await first.getByLabel('Set completed').check()
  await expect(second.getByLabel('Actual load (kg)')).toHaveValue('')
  await expect(second.getByLabel('Actual load convention', { exact: true })).toHaveValue('Unknown convention')
  await expect(round2.getByLabel('Actual load (kg)').first()).toHaveValue('')
  await expect(round1.getByText('Rest 120 s after the pair.')).toBeVisible()
  const order = await round1.getByRole('article').evaluateAll(items => items.map(item => item.getAttribute('aria-label')))
  expect(order).toEqual(['A1 Barbell bench press', 'A2 Barbell bent over row'])
  await section.locator('label').filter({ hasText: /^Review$/ }).click()
  await expect(section.getByText('Actual: 52.5 kg (total external load) · 7 reps · RIR not recorded')).toBeVisible()
  await expect(section.getByRole('spinbutton')).toHaveCount(0)
  await section.locator('label').filter({ hasText: /^Client$/ }).click()
  await expect(first.getByLabel('Actual load (kg)')).toHaveValue('52.5')
  await expect(first.getByLabel('Actual load convention', { exact: true })).toHaveValue('Total external load')
  await section.getByRole('button', { name: 'Reset block' }).click()
  await expect(first.getByLabel('Actual load (kg)')).toHaveValue('')
  await expect(first.getByLabel('Set completed')).not.toBeChecked()
})

