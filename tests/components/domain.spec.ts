test('request errors retain form entries; sync retry is an explicit state callback', async ({ page }) => {
  const accounts = page.locator('#accounts')
  await accounts.getByRole('switch', { name: 'Simulate request failure' }).check()
  await accounts.getByRole('textbox', { name: 'Client name' }).fill('Taylor')
  await accounts.getByRole('textbox', { name: 'Email' }).fill('taylor@example.test')
  await accounts.getByRole('button', { name: 'Invite client', exact: true }).click()
  await expect(accounts.getByText('Example server error. Your entries are still here.')).toBeVisible()
  await expect(accounts.getByRole('textbox', { name: 'Client name' })).toHaveValue('Taylor')
  await accounts.getByRole('switch', { name: 'Simulate request failure' }).uncheck()
  await accounts.getByRole('button', { name: 'Invite client', exact: true }).click()
  await expect(accounts.getByRole('status')).toHaveText('Request accepted in this demo.')
  const states = page.locator('#states')
  await states.getByRole('button', { name: 'Retry sync' }).click()
  await expect(states.getByText('Workout synced', { exact: true })).toBeVisible()
  await expect(states.getByRole('button', { name: 'Retry sync' })).toHaveCount(0)
})

