test('conversation failures retain drafts, retry sends once and clears only on success', async ({ page }) => {
  const section = page.locator('#conversation')
  await section.getByRole('switch', { name: 'Simulate message failure' }).check()
  await section.getByLabel('Message', { exact: true }).fill('Can I use a lighter load?')
  await section.getByRole('button', { name: 'Send message' }).click()
  await expect(section.getByRole('alert')).toContainText('Your message is still here.')
  await expect(section.getByLabel('Message', { exact: true })).toHaveValue('Can I use a lighter load?')
  await section.getByRole('switch', { name: 'Simulate message failure' }).uncheck()
  await section.getByRole('button', { name: 'Send message' }).click()
  await expect(section.getByRole('region', { name: 'Conversation messages' }).getByText('Can I use a lighter load?', { exact: true })).toHaveCount(1)
  await expect(section.getByLabel('Message', { exact: true })).toHaveValue('')
  await expect(section.getByRole('button', { name: 'Send message' })).toBeDisabled()
})

